function analyzeVacancy() {
  const raw = $("#vacancy-text").value.trim();
  if (raw.length < 25) { showToast("Pega una descripción un poco más completa para analizarla."); return; }
  const vacancy = normalize(raw);
  const corpus = buildSearchCorpus();
  const matches = [];
  const gaps = [];
  const trainingOnly = [];
  TERMS.forEach((term) => {
    const inVacancy = term.keys.some((key) => vacancy.includes(key));
    if (!inVacancy) return;
    const found = term.keys.some((key) => corpus.includes(key));
    if (!found) { gaps.push(term.label); return; }
    const onlyTraining = term.label.includes("Impactos") || term.label.includes("Normativa");
    if (onlyTraining) trainingOnly.push(term.label);
    else matches.push(term.label);
  });
  const requested = matches.length + gaps.length + trainingOnly.length;
  const result = $("#match-result");
  result.dataset.analysis = JSON.stringify({ raw, matches, gaps, trainingOnly });
  if (requested === 0) {
    result.innerHTML = `<div class="result-content"><span class="result-status">LECTURA PRELIMINAR</span><h3>No se detectaron términos de la lista de referencia.</h3><p>Revisa la descripción manualmente. La herramienta usa categorías básicas y no reemplaza la lectura íntegra de las bases.</p></div>`;
  } else {
    result.innerHTML = `<div class="result-content"><span class="result-status">LECTURA PRELIMINAR · ${requested} TÉRMINOS</span><h3>${matches.length} coincidencia${matches.length === 1 ? "" : "s"} para revisar</h3>
      ${matches.length ? `<div class="result-group"><b>Experiencia / herramientas relacionadas</b><ul>${matches.map((item) => `<li><span class="check">✓</span>${escapeHTML(item)}</li>`).join("")}</ul></div>` : ""}
      ${trainingOnly.length ? `<div class="result-group result-training"><b>Conocimiento o formación; confirma la evidencia</b><ul>${trainingOnly.map((item) => `<li><span class="check">◦</span>${escapeHTML(item)}</li>`).join("")}</ul></div>` : ""}
      ${gaps.length ? `<div class="result-group result-gap"><b>No localizado en el perfil cargado</b><ul>${gaps.map((item) => `<li><span class="check">!</span>${escapeHTML(item)}</li>`).join("")}</ul><p>Verifica si tienes evidencia adicional antes de incluirlo en tu postulación.</p></div>` : ""}
      <p class="result-footnote">Coincidencias textuales orientativas. No son evaluación oficial ni aseguran cumplimiento de requisitos.</p></div>`;
  }
  $("#application-name").focus({ preventScroll: true });
}

const STORE_KEY = "miguel-portfolio-applications-v1";
function getApplications() {
  try { const rows = JSON.parse(localStorage.getItem(STORE_KEY) || "[]"); return Array.isArray(rows) ? rows : []; }
  catch { return []; }
}
function saveApplications(rows) {
  try { localStorage.setItem(STORE_KEY, JSON.stringify(rows)); renderApplications(); return true; }
  catch { showToast("El navegador no permitió guardar. Revisa el almacenamiento local."); return false; }
}
function renderApplications() {
  const rows = getApplications();
  const host = $("#saved-applications");
  host.innerHTML = rows.length ? `<h3>Vacantes guardadas <span>${rows.length}</span></h3>${rows.map((row) => `<article class="saved-row"><div><b>${escapeHTML(row.name)}</b><span>${escapeHTML(row.date)}</span></div><span class="saved-status">En preparación</span><button type="button" data-remove="${escapeHTML(row.id)}" aria-label="Eliminar ${escapeHTML(row.name)}">×</button></article>`).join("")}` : "";
}
function saveCurrentApplication() {
  const name = $("#application-name").value.trim();
  const result = $("#match-result");
  if (!name) { showToast("Escribe el nombre del puesto para guardarlo."); $("#application-name").focus(); return; }
  if (!result.dataset.analysis) { showToast("Analiza primero los requisitos de la convocatoria."); return; }
  const rows = getApplications();
  rows.unshift({ id: crypto.randomUUID ? crypto.randomUUID() : String(Date.now()), name, date: new Date().toLocaleDateString("es-PE"), analysis: JSON.parse(result.dataset.analysis) });
  if (saveApplications(rows)) { $("#application-name").value = ""; showToast("Vacante guardada en este navegador."); }
}

